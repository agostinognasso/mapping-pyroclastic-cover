# 39_coverage_figure.R - Figure 7 and its table: coverage within classes
# Drawn from the results saved by 17 (pi_calibration.rds), without refitting
# anything:
#  - one point per class with the 95% Wilson interval (Wilson 1927) for a
#    binomial proportion. It treats the points as independent: with spatial
#    dependence the effective sample size is smaller and the true intervals
#    are wider, so these are a lower bound on the uncertainty;
#  - the number of points n under each class;
#  - the band between 0.85 and 0.95 is the practical tolerance of 5
#    percentage points, not a test;
#  - Okabe and Ito colours different from the green, amber and red of the
#    regimes;
#  - the x axis title in every panel, instead of sub-captions.
source("R/00_setup.R")
S  <- readRDS(file.path(PATHS$models, "pi_calibration.rds"))$RF
wilson <- function(p, n, z = qnorm(0.975)) {
  den <- 1 + z^2 / n
  ctr <- (p + z^2 / (2 * n)) / den
  hw  <- z / den * sqrt(p * (1 - p) / n + z^2 / (4 * n^2))
  cbind(lo = pmax(0, ctr - hw), hi = pmin(1, ctr + hw))
}
prep <- function(t, labs) {
  w <- wilson(t$coverage_90, t$n)
  data.frame(stratum = t$stratum, label = labs, n = t$n, cov = t$coverage_90,
             lo = w[, "lo"], hi = w[, "hi"])
}
P <- list(
  yhat  = prep(S$by_yhat, sprintf("%s\n(%.0f cm)", S$by_yhat$stratum,
                                  S$by_yhat$mean_yhat)),
  slope = prep(S$by_slope, c("≤ 5°", "5–15°", "15–30°",
                             "> 30°")),
  sect  = prep(S$by_massif, S$by_massif$stratum))

TOL <- 0.05
COL_IN  <- "#56B4E9"   # Okabe-Ito sky blue: within the tolerance
COL_OUT <- "#CC79A7"   # Okabe-Ito reddish purple: outside the tolerance
panel39 <- function(x, xlab, ylab = "") {
  k <- nrow(x); at <- seq_len(k)
  plot(NA, xlim = c(0.5, k + 0.5), ylim = c(0.55, 1.02), xaxt = "n",
       xlab = "", ylab = ylab, las = 1)
  rect(0, 0.9 - TOL, k + 1, 0.9 + TOL, col = "grey92", border = NA)
  abline(h = 0.9, lty = 2)
  segments(at, x$lo, at, x$hi, lwd = 1.6, col = "grey25")
  points(at, x$cov, pch = 21, cex = 1.7, lwd = 1.2,
         bg = ifelse(abs(x$cov - 0.9) < TOL, COL_IN, COL_OUT))
  axis(1, at = at, labels = x$label, padj = 0.5, cex.axis = 0.85, tick = FALSE)
  # sample size inside the panel, at the bottom: under the axis it would
  # overlap with six classes
  text(at, 0.575, sprintf("n=%s", formatC(x$n, big.mark = " ", format = "d")),
       cex = 0.62, col = "grey30")
  mtext(xlab, side = 1, line = 3.6, cex = 0.75)
  box()
}
save_base("F52_conditional_coverage", function() {
  op <- par(mfrow = c(1, 3), mar = c(5.2, 4.2, 1, 0.8), mgp = c(2.8, 0.7, 0))
