}, w = 1300 / 150, h = 720 / 150)

# ---- Table of the coverage within classes -------------------------------------
f3 <- function(x) formatC(x, format = "f", digits = 3)
thn <- function(x) gsub(",", "\\\\,", formatC(x, big.mark = ",", format = "d"))
grp <- c(yhat = "Quartile of predicted thickness", slope = "Slope class",
         sect = "Regional sector")
lab_tex <- list(yhat = sprintf("%s (mean $%.0f$~cm)", S$by_yhat$stratum,
                               S$by_yhat$mean_yhat),
                slope = c("$\\le 5^{\\circ}$", "$5$--$15^{\\circ}$",
                          "$15$--$30^{\\circ}$", "$> 30^{\\circ}$"),
                sect = S$by_massif$stratum)
rows <- unlist(lapply(names(P), function(g) {
  x <- P[[g]]
  # no \multicolumn: at the top of a file read with \input inside a LaTeX
  # table it gives "Misplaced \omit"
  c(sprintf("\\emph{%s} & & & \\\\", grp[[g]]),
    sprintf("\\quad %s & $%s$ & $%s$ & $%s$--$%s$\\\\", lab_tex[[g]], thn(x$n),
            f3(x$cov), f3(x$lo), f3(x$hi)))
}))
writeLines(c("% tab_supp_cov.tex -- generated by R/39_coverage_figure.R. Do not edit by hand.",
             rows), file.path(PATHS$paper, "tab_supp_cov.tex"))
out <- do.call(rbind, lapply(names(P), function(g) cbind(group = g, P[[g]][, -2])))
write.csv(out, file.path(PATHS$tables, "T57_coverage_wilson.csv"), row.names = FALSE)
print(out, row.names = FALSE)
