# 29_supp_tables.R - LaTeX tables of the supplement: they show, and not only
# state, the skewness of the response and the weakness of the univariate
# correlations. Writes PATHS$paper/tab_supp_desc.tex with the tables of
# descriptive statistics and of Spearman correlations.
source("R/00_setup.R")

d  <- readRDS(file.path(PATHS$models, "data_clean.rds"))
df <- d$model_df; pv <- d$predictors

fmt <- function(x, k = 2) formatC(x, format = "f", digits = k, big.mark = "\\,")

# ---- S1: descriptives of the response + covariates ---------------------------
vars <- c(TARGET, pv)
desc <- do.call(rbind, lapply(vars, function(v) {
  x <- df[[v]]
  data.frame(var = v, n = sum(!is.na(x)),
             mean = mean(x, na.rm = TRUE), sd = sd(x, na.rm = TRUE),
             min = min(x, na.rm = TRUE),
             q25 = quantile(x, .25, na.rm = TRUE),
             med = median(x, na.rm = TRUE),
             q75 = quantile(x, .75, na.rm = TRUE),
             max = max(x, na.rm = TRUE), row.names = NULL)
}))
# sample skewness (g1)
desc$skew <- vapply(vars, function(v) {
  x <- df[[v]][!is.na(df[[v]])]; m <- mean(x)
  mean((x - m)^3) / (mean((x - m)^2))^1.5 }, numeric(1))

lbl <- c(thick_cm = "$z$ (response, cm)", ThickIso = "$z_{0}$ (cm)",
         Elevation = "Altitude (m)", Slope = "Slope (deg)",
         Aspect = "Aspect (deg)", Curvature = "Curvature",
         PlanCurv = "Plan curvature", ProfCurv = "Profile curvature",
         DistHydnet = "Distance to hydrographic network (m)",
         FlowAcc = "Flow accumulation", FlowDir = "Flow direction (deg)",
         lnSPI = "ln(SPI)", STI = "STI", TWI = "TWI",
         NDVI = "NDVI", NCI = "NCI", MSAVI2 = "MSAVI$_{2}$")
desc$lab <- ifelse(desc$var %in% names(lbl), lbl[desc$var], desc$var)

rows1 <- sprintf("%s & %s & %s & %s & %s & %s & %s & %s & %s \\\\",
                 desc$lab, fmt(desc$mean), fmt(desc$sd), fmt(desc$min),
                 fmt(desc$q25), fmt(desc$med), fmt(desc$q75), fmt(desc$max),
                 fmt(desc$skew))

# ---- S2: Spearman correlation of each covariate with the response -----------
sp <- data.frame(var = pv,
  rho = vapply(pv, function(v)
    suppressWarnings(cor(df[[TARGET]], df[[v]], method = "spearman",
                         use = "complete.obs")), numeric(1)),
  row.names = NULL)
sp <- sp[order(-abs(sp$rho)), ]
sp$lab <- ifelse(sp$var %in% names(lbl), lbl[sp$var], sp$var)
rows2 <- sprintf("%s & %s \\\\", sp$lab, formatC(sp$rho, format = "f", digits = 3))

tex <- c(
"% tab_supp_desc.tex -- generated by R/29_supp_tables.R. Do not edit by hand.",
"\\begin{table}[h!]\\centering",
"\\caption{Descriptive statistics of the response and the sixteen predictors on",
"the modelling set. The response $z$ is strongly right skewed; $g_1$ is the",
"sample skewness.}",
"\\label{tab:desc}",
"\\footnotesize",
"\\setlength{\\tabcolsep}{4pt}",
"\\begin{tabular}{@{}lrrrrrrrr@{}}",
"\\toprule",
"Variable & mean & sd & min & 25\\% & median & 75\\% & max & $g_1$\\\\",
"\\midrule",
rows1,
"\\bottomrule",
"\\end{tabular}",
sprintf("\\\\[2pt]{\\scriptsize $n=%s$ for every variable; no missing values.}",
        formatC(nrow(df), format = "d", big.mark = "\\,")),
"\\end{table}",
"",
"\\begin{table}[h!]\\centering",
"\\caption{Univariate Spearman rank correlation between the response $z$ and",
"each predictor, ordered by absolute value. No association reaches",
"$|\\rho|=0.25$.}",
"\\label{tab:spear}",
"\\footnotesize",
"\\begin{tabular}{@{}lr@{}}",
"\\toprule",
"Predictor & $\\rho$ (Spearman, with $z$)\\\\",
"\\midrule",
rows2,
"\\bottomrule",
"\\end{tabular}",
"\\end{table}")

writeLines(tex, file.path(PATHS$paper, "tab_supp_desc.tex"))
cat("\n==== max |rho| =", round(max(abs(sp$rho)), 3),
    "| skew(z) =", round(desc$skew[desc$var == TARGET], 2), "\n")
message("29_supp_tables OK -> ", file.path(PATHS$paper, "tab_supp_desc.tex"))
